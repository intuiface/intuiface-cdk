import fs from 'fs-extra';
import path from 'path';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { runMigrateCommand } from '../../src/commands/migrate.command.js';
import { WORKSPACE_BUILD_DEV_DEPENDENCIES } from '../../src/services/generator.service.js';
import { cliRoot, createTempDir, mockProcessExit, removeTempDir, useCwd, writeFiles } from '../helpers/test-utils.js';

const cliPackageVersion: string = fs.readJsonSync(path.join(cliRoot, 'package.json')).version;

/** package.json of a project created by the 2.x interface-asset schematic. */
const standalonePackageJson = (buildScript: string): Record<string, unknown> => ({
    name: 'my-project',
    version: '1.0.0',
    scripts: {
        'build': buildScript,
        'build:debug': `${buildScript} -d`,
        'lint': 'npx eslint .'
    },
    dependencies: {
        '@intuiface/cli': '2.1.0',
        '@intuiface/core': '2.1.0',
        'tslib': '^2.6.2'
    },
    devDependencies: {
        'ts-loader': '^9.4.2',
        'typescript': '~5.4.0',
        'webpack': '^5.76.0',
        'webpack-cli': '^5.0.1',
        'eslint': '^8.57.0'
    }
});

/** tsconfig.json of a 2.1-era project (with a comment, as generated by the schematics). */
const legacyTsConfig = `{
    // generated by the schematic
    "compilerOptions": {
        "outDir": "./dist",
        "experimentalDecorators": true,
        "moduleResolution": "node",
        "downlevelIteration": true,
        "target": "ES2020"
    },
    "include": ["src/**/*.ts"]
}
`;

describe('migrate command', () =>
{
    let dir: string;
    let restoreCwd: () => void;

    beforeEach(() =>
    {
        dir = createTempDir('cli-migrate');
        restoreCwd = useCwd(dir);
        // npm sets INIT_CWD when the tests run through npm/npx; the pre-v2 migration reads it first
        vi.stubEnv('INIT_CWD', dir);
    });

    afterEach(() =>
    {
        vi.unstubAllEnvs();
        restoreCwd();
        removeTempDir(dir);
    });

    it('leaves a workspace unchanged', () =>
    {
        writeFiles(dir, {
            'intuiface.workspace.json': { version: 1, name: 'ws', items: [] },
            'package.json': { name: 'ws', scripts: { build: 'npx intuiface-cli build --all' } }
        });
        const before = fs.readFileSync(path.join(dir, 'package.json'), 'utf8');

        runMigrateCommand();

        expect(fs.readFileSync(path.join(dir, 'package.json'), 'utf8')).toBe(before);
    });

    it('stops when the project type is unknown', () =>
    {
        writeFiles(dir, { 'package.json': { name: 'other', scripts: { build: 'tsc' } } });
        mockProcessExit();

        expect(() => runMigrateCommand()).toThrow('process.exit(-2)');
        expect(fs.existsSync(path.join(dir, 'intuiface.workspace.json'))).toBe(false);
    });

    describe('2.x project to workspace', () =>
    {
        it('migrates an interface asset project', () =>
        {
            writeFiles(dir, {
                'package.json': standalonePackageJson('npx intuiface-cli build -n MyAsset'),
                'tsconfig.json': legacyTsConfig,
                'webpack.config.js': 'module.exports = {};',
                'webpack-debug.config.js': 'module.exports = {};',
                'src/MyAsset.ts': 'export class MyAsset {}\n'
            });

            runMigrateCommand();

            expect(fs.readJsonSync(path.join(dir, 'intuiface.workspace.json'))).toEqual({
                version: 1,
                name: 'my-project',
                items: [{ name: 'MyAsset', type: 'interface-asset', entry: 'src/MyAsset.ts' }]
            });
            expect(fs.existsSync(path.join(dir, 'webpack.config.js'))).toBe(false);
            expect(fs.existsSync(path.join(dir, 'webpack-debug.config.js'))).toBe(false);
            expect(fs.existsSync(path.join(dir, 'src', 'MyAsset.ts'))).toBe(true);
        });

        it('updates the build scripts and the build toolchain', () =>
        {
            writeFiles(dir, { 'package.json': standalonePackageJson('npx intuiface-cli build -n MyAsset') });

            runMigrateCommand();

            const packageJson = fs.readJsonSync(path.join(dir, 'package.json'));
            expect(packageJson.scripts).toEqual({
                'build': 'npx intuiface-cli build --all',
                'build:debug': 'npx intuiface-cli build --all --debug',
                'lint': 'npx eslint .'
            });
            expect(packageJson.devDependencies).toEqual({ ...WORKSPACE_BUILD_DEV_DEPENDENCIES, eslint: '^8.57.0' });
            expect(packageJson.dependencies).toEqual({
                '@intuiface/cli': cliPackageVersion,
                '@intuiface/core': cliPackageVersion,
                'tslib': '^2.6.2'
            });
        });

        it('updates tsconfig.json for TypeScript 6', () =>
        {
            writeFiles(dir, {
                'package.json': standalonePackageJson('npx intuiface-cli build -n MyAsset'),
                'tsconfig.json': legacyTsConfig
            });

            runMigrateCommand();

            const tsconfig = fs.readJsonSync(path.join(dir, 'tsconfig.json'));
            expect(tsconfig.compilerOptions).toEqual({
                outDir: './dist',
                experimentalDecorators: true,
                moduleResolution: 'bundler',
                target: 'ES2020',
                rootDir: './src'
            });
            expect(tsconfig.include).toEqual(['src/**/*.ts']);
        });

        it('keeps an up-to-date tsconfig.json untouched', () =>
        {
            const tsconfig = '{\n  // keep me\n  "compilerOptions": { "rootDir": "./src", "moduleResolution": "bundler" }\n}\n';
            writeFiles(dir, {
                'package.json': standalonePackageJson('npx intuiface-cli build -n MyAsset'),
                'tsconfig.json': tsconfig
            });

            runMigrateCommand();

            expect(fs.readFileSync(path.join(dir, 'tsconfig.json'), 'utf8')).toBe(tsconfig);
        });

        it('migrates a binding converter project with its default icon', () =>
        {
            writeFiles(dir, {
                'package.json': standalonePackageJson('npx intuiface-cli build -n MyConverter -t binding-converter'),
                'icon_converter_32.png': 'png'
            });

            runMigrateCommand();

            expect(fs.readJsonSync(path.join(dir, 'intuiface.workspace.json')).items).toEqual([{
                name: 'MyConverter',
                type: 'binding-converter',
                entry: 'src/MyConverter.ts',
                icon: 'icon_converter_32.png'
            }]);
        });

        it('keeps the icon of the build script', () =>
        {
            writeFiles(dir, { 'package.json': standalonePackageJson('npx intuiface-cli build -t interface-asset -i ./assets/icon.png -n MyAsset') });

            runMigrateCommand();

            expect(fs.readJsonSync(path.join(dir, 'intuiface.workspace.json')).items).toEqual([{
                name: 'MyAsset',
                type: 'interface-asset',
                entry: 'src/MyAsset.ts',
                icon: './assets/icon.png'
            }]);
        });

        it('names the workspace after the folder when package.json has no name', () =>
        {
            const packageJson = standalonePackageJson('npx intuiface-cli build -n MyAsset');
            delete packageJson.name;
            writeFiles(dir, { 'package.json': packageJson });

            runMigrateCommand();

            expect(fs.readJsonSync(path.join(dir, 'intuiface.workspace.json')).name).toBe(path.basename(dir));
        });

        // Known bug B1 (PR #119 review): migrate overwrites build dependencies, even newer ones.
        // Remove `.fails` once only lower versions are bumped.
        it.fails('does not downgrade a newer build dependency', () =>
        {
            const packageJson = standalonePackageJson('npx intuiface-cli build -n MyAsset');
            (packageJson.devDependencies as Record<string, string>).webpack = '^99.0.0';
            writeFiles(dir, { 'package.json': packageJson });

            runMigrateCommand();

            expect(fs.readJsonSync(path.join(dir, 'package.json')).devDependencies.webpack).toBe('^99.0.0');
        });
    });

    describe('pre-2.0 project to workspace', () =>
    {
        const writePreV2Project = (indexIfd: string): void =>
        {
            writeFiles(dir, {
                'package.json': {
                    name: 'old-project',
                    scripts: { build: 'npm run cleanDist && webpack', cleanDist: 'rimraf dist', cleanTmp: 'rimraf tmp' },
                    dependencies: { '@intuiface/core': '1.2.0' },
                    devDependencies: { typescript: '~4.9.0' }
                },
                'tsconfig.json': '{\n  "compilerOptions": {\n    "target": "es2017",\n    "downlevelIteration": true,\n  },\n}\n',
                'tsconfig.ifd.json': '{}',
                'webpack.config.js': 'module.exports = {};',
                'src/index_ifd.ts': indexIfd,
                'src/index.js': '',
                'src/package.json': '{}',
                'src/OldAsset.ts': 'export class OldAsset {}\n',
                'dist/old.js': ''
            });
        };

        it('detects the asset imported by index_ifd.ts', () =>
        {
            writePreV2Project(`const ia = await import('./OldAsset.js');\n`);

            runMigrateCommand();

            expect(fs.readJsonSync(path.join(dir, 'intuiface.workspace.json'))).toEqual({
                version: 1,
                name: path.basename(dir),
                items: [{ name: 'OldAsset', type: 'interface-asset', entry: 'src/OldAsset.ts' }]
            });
        });

        it('detects the asset instantiated by index_ifd.ts', () =>
        {
            writePreV2Project(`import { OldAsset } from './OldAsset';\nconst ia = new OldAsset();\n`);

            runMigrateCommand();

            expect(fs.readJsonSync(path.join(dir, 'intuiface.workspace.json')).items[0].name).toBe('OldAsset');
        });

        it('updates package.json and tsconfig.json and removes the obsolete files', () =>
        {
            writePreV2Project(`const ia = await import('./OldAsset.js');\n`);

            runMigrateCommand();

            const packageJson = fs.readJsonSync(path.join(dir, 'package.json'));
            expect(packageJson.scripts).toEqual({
                'build': 'npx intuiface-cli build --all',
                'build:debug': 'npx intuiface-cli build --all --debug'
            });
            expect(packageJson.devDependencies).toMatchObject(WORKSPACE_BUILD_DEV_DEPENDENCIES);
            expect(packageJson.dependencies['@intuiface/core']).toBe(cliPackageVersion);

            const tsconfig = fs.readJsonSync(path.join(dir, 'tsconfig.json'));
            expect(tsconfig.compilerOptions).toEqual({
                target: 'ES2022',
                rootDir: './src',
                outDir: './dist',
                useDefineForClassFields: false,
                moduleResolution: 'bundler'
            });
            expect(tsconfig.include).toEqual(['**/src/**/*.ts']);

            for (const removed of ['src/index_ifd.ts', 'src/index.js', 'src/package.json', 'tsconfig.ifd.json', 'webpack.config.js', 'dist'])
            {
                expect(fs.existsSync(path.join(dir, removed)), removed).toBe(false);
            }
            expect(fs.existsSync(path.join(dir, 'src', 'OldAsset.ts'))).toBe(true);
        });

        it('stops when the asset cannot be found in index_ifd.ts', () =>
        {
            writePreV2Project('// nothing to detect\n');
            mockProcessExit();

            expect(() => runMigrateCommand()).toThrow('process.exit(-2)');
            expect(fs.existsSync(path.join(dir, 'intuiface.workspace.json'))).toBe(false);
            expect(fs.existsSync(path.join(dir, 'src', 'index_ifd.ts'))).toBe(true);
        });
    });
});
