import fs from 'fs-extra';
import path from 'path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { readWorkspaceTemplateFile } from '../../src/services/generator.service.js';
import { analyzeLegacyWebpackConfig, LegacyConfigAnalysis, migrateWebpackConfigFiles, renderWebpackConfig } from '../../src/services/webpack-migration.service.js';
import { createTempDir, removeTempDir, repoRoot, writeFiles } from '../helpers/test-utils.js';

const schematicsDir = path.join(repoRoot, 'libs', 'tools', 'schematics');

/** Files of the repository may be checked out with Windows line endings. */
const toLf = (text: string): string => text.replace(/\r\n/g, '\n');

/** webpack.config.js and webpack-debug.config.js of the 2.x interface-asset schematic, for an item. */
const interfaceAssetConfig = (name: string, file: string): string =>
    toLf(fs.readFileSync(path.join(schematicsDir, 'interface-asset-schematics', 'src', 'create', 'files', file), 'utf8')).replace(/<%= IAName %>/g, name);

/** webpack.config.js of the 2.x binding-converter schematic, for an item. */
const bindingConverterConfig = (name: string): string =>
    toLf(fs.readFileSync(path.join(schematicsDir, 'binding-converter-schematics', 'src', 'create', 'files', 'webpack.config.js'), 'utf8'))
        .replace(/<%= bindingConverterName %>/g, name);

/** webpack.config.js of the pre-2.0 schematic (before the CLI): no output path, entry src/index.js. */
const preV2Config = (name: string): string => `const ModuleFederationPlugin = require("webpack").container.ModuleFederationPlugin;

module.exports = {
    module: {
        rules: [{
            test: /\\.tsx?$/,
            use: 'ts-loader',
            exclude: /node_modules/
        }]
    },
    output: {
        publicPath: "auto",
    },
    resolve: {
        extensions: ['.tsx', '.ts', '.js'],
    },
    plugins: [
        new ModuleFederationPlugin({
            name: "${name}",
            filename: "${name}.js",
            exposes: {
                "./${name}": {
                    import : "./src/${name}.ts",
                    name: '${name}.module'
                }
            },
            shared: {
                "@intuiface/core": {
                    singleton: true,
                    strictVersion: false
                }
            }
        })
    ],
    entry: './src/index.js'
};`;

/** The 2.x webpack.config.js of MyAsset, with `extra` inserted at the end of the configuration object. */
const customizedConfig = (extra: string, preamble: string = ''): string =>
    `${preamble}${interfaceAssetConfig('MyAsset', 'webpack.config.js').replace(/\n};\s*$/, `,\n${extra}\n};\n`)}`;

const analyzeBase = (text: string): LegacyConfigAnalysis => analyzeLegacyWebpackConfig('webpack.config.js', text, 'MyAsset', 'base');

const analyzeDebug = (text: string): LegacyConfigAnalysis => analyzeLegacyWebpackConfig('webpack-debug.config.js', text, 'MyAsset', 'debug');

const template = toLf(readWorkspaceTemplateFile('webpack.config.cjs'));

/** The function body of the template once the customisations are inserted before `return config;`. */
const withBody = (body: string): string => template.replace('    return config;', `${body}\n\n    return config;`);

// eslint-disable-next-line @typescript-eslint/no-explicit-any
type CustomizeFunction = (config: any, context: { item: { name: string }; debug: boolean }) => any;

/**
 * Evaluate a webpack.config.cjs written by the migration. `require` only provides `webpack` (with DefinePlugin).
 */
const loadCustomization = (text: string): CustomizeFunction =>
{
    class DefinePlugin
    {
        // eslint-disable-next-line @typescript-eslint/no-explicit-any
        public constructor(public definitions: any)
        {
        }
    }

    const stubRequire = (id: string): unknown =>
    {
        if (id !== 'webpack')
        {
            throw new Error(`Unexpected require('${id}')`);
        }
        return { DefinePlugin };
    };
    const module = { exports: {} as unknown };
    new Function('require', 'module', 'exports', '__dirname', text)(stubRequire, module, module.exports, '/workspace');
    return module.exports as CustomizeFunction;
};

/** A configuration as the CLI generates it, reduced to what the migrated code changes. */
// eslint-disable-next-line @typescript-eslint/no-explicit-any
const generatedConfig = (): any => ({
    mode: 'production',
    module: { rules: [{ use: 'ts-loader' }] },
    output: { publicPath: 'auto', path: '/workspace/dist/MyAsset' },
    resolve: { extensions: ['.tsx', '.ts', '.js'] },
    plugins: ['ModuleFederationPlugin']
});

describe('webpack config migration', () =>
{
    describe('files generated by the schematics', () =>
    {
        it.each([
            ['2.x interface asset', interfaceAssetConfig('MyAsset', 'webpack.config.js')],
            ['2.x binding converter', bindingConverterConfig('MyAsset')],
            ['pre-2.0 interface asset', preV2Config('MyAsset')],
            ['Windows line endings', interfaceAssetConfig('MyAsset', 'webpack.config.js').replace(/\n/g, '\r\n')],
            ['an empty configuration', 'module.exports = {};']
        ])('finds nothing to move in webpack.config.js (%s)', (description, text) =>
        {
            expect(analyzeBase(text)).toMatchObject({ statements: [], customizations: [], unsupported: [] });
        });

        it('finds nothing to move in webpack-debug.config.js', () =>
        {
            expect(analyzeDebug(interfaceAssetConfig('MyAsset', 'webpack-debug.config.js'))).toMatchObject({ statements: [], customizations: [], unsupported: [] });
        });

        it('keeps the template unchanged', () =>
        {
            const analyses = [
                analyzeBase(interfaceAssetConfig('MyAsset', 'webpack.config.js')),
                analyzeDebug(interfaceAssetConfig('MyAsset', 'webpack-debug.config.js'))
            ];

            expect(renderWebpackConfig(template, analyses)).toBe(template);
        });
    });

    it('keeps the line endings of the template', () =>
    {
        const analysis = analyzeBase(customizedConfig(`    externals: {\n        fs: 'commonjs fs'\n    }`, `const os = require('os');\nconst platform = os.platform();\n`));
        const windowsTemplate = template.replace(/\n/g, '\r\n');

        const rendered = renderWebpackConfig(windowsTemplate, [analysis]);

        expect(rendered.replace(/\r\n/g, '')).not.toContain('\n');
        expect(toLf(rendered)).toBe(renderWebpackConfig(template, [analysis]));
    });

    describe('webpack.config.js customisations', () =>
    {
        it('moves externals with their comments, and drops the requires only the generated part used', () =>
        {
            const analysis = analyzeBase(customizedConfig([
                '    // Modules provided by the player',
                '    externals: {',
                `        serialport: 'commonjs serialport',`,
                `        '@brightsign/deviceinfo': 'commonjs @brightsign/deviceinfo'`,
                '    }'
            ].join('\n')));

            expect(analysis.unsupported).toEqual([]);
            expect(analysis.customizations.map((customization) => customization.name)).toEqual(['externals']);
            expect(renderWebpackConfig(template, [analysis])).toBe(withBody([
                '    // Moved from webpack.config.js by intuiface-cli migrate',
                '    // Modules provided by the player',
                '    config.externals = {',
                `        serialport: 'commonjs serialport',`,
                `        '@brightsign/deviceinfo': 'commonjs @brightsign/deviceinfo'`,
                '    };'
            ].join('\n')));
        });

        it('applies the moved externals to the generated configuration', async () =>
        {
            const analysis = analyzeBase(customizedConfig(`    externals: { fs: 'commonjs fs' },\n    externalsPresets: { electron: true },\n    target: 'electron-renderer'`));
            const customize = loadCustomization(renderWebpackConfig(template, [analysis]));

            const config = await customize(generatedConfig(), { item: { name: 'MyAsset' }, debug: false });

            expect(config).toEqual({
                ...generatedConfig(),
                externals: { fs: 'commonjs fs' },
                externalsPresets: { electron: true },
                target: 'electron-renderer'
            });
        });

        it('moves the top-level declarations the customisations use', () =>
        {
            const analysis = analyzeBase(customizedConfig(
                '    externals,\n    resolve2: path.join(__dirname, \'lib\')',
                `// Provided by BrightSign\nconst externals = { '@brightsign/registry': 'commonjs @brightsign/registry' };\n`
            ));

            expect(analysis.unsupported).toEqual([]);
            const rendered = renderWebpackConfig(template, [analysis]);
            expect(rendered.startsWith([
                `// Provided by BrightSign`,
                `const externals = { '@brightsign/registry': 'commonjs @brightsign/registry' };`,
                `const path = require('path');`,
                '',
                '/**'
            ].join('\n'))).toBe(true);
            expect(rendered).toContain('    config.externals = externals;\n    config.resolve2 = path.join(__dirname, \'lib\');\n');
            expect(rendered).not.toContain('ModuleFederationPlugin');
        });

        it('adds the other plugins and rules to the generated ones', async () =>
        {
            const text = interfaceAssetConfig('MyAsset', 'webpack.config.js')
                .replace(`const path = require('path');`, `const path = require('path');\nconst webpack = require('webpack');`)
                .replace(/\n(\s*)\}\)\n(\s*)\],/, `\n$1}),\n$1new webpack.DefinePlugin({ PLAYER: JSON.stringify('brightsign') })\n$2],`)
                .replace(/exclude: \/node_modules\/\n(\s*)\}\]/, `exclude: /node_modules/\n$1}, {\n$1    test: /\\.txt$/,\n$1    type: 'asset/source'\n$1}]`);
            const analysis = analyzeBase(text);

            expect(analysis.unsupported).toEqual([]);
            expect(analysis.customizations.map((customization) => customization.name)).toEqual(['module.rules', 'plugins']);
            const config = await loadCustomization(renderWebpackConfig(template, [analysis]))(generatedConfig(), { item: { name: 'MyAsset' }, debug: false });
            expect(config.module.rules).toEqual([{ use: 'ts-loader' }, { test: /\.txt$/, type: 'asset/source' }]);
            expect(config.plugins).toHaveLength(2);
            expect(config.plugins[1].definitions).toEqual({ PLAYER: '"brightsign"' });
        });

        it('sets the resolve and output options the CLI does not generate', async () =>
        {
            const text = interfaceAssetConfig('MyAsset', 'webpack.config.js')
                .replace(`extensions: ['.tsx', '.ts', '.js'],`, `extensions: ['.tsx', '.ts', '.js'],\n        fallback: { fs: false }`)
                .replace(`publicPath: "auto",`, `publicPath: "auto",\n        clean: true,`);
            const analysis = analyzeBase(text);

            expect(analysis.unsupported).toEqual([]);
            expect(analysis.customizations.map((customization) => customization.name)).toEqual(['output.clean', 'resolve.fallback']);
            const config = await loadCustomization(renderWebpackConfig(template, [analysis]))(generatedConfig(), { item: { name: 'MyAsset' }, debug: false });
            expect(config.output).toEqual({ publicPath: 'auto', path: '/workspace/dist/MyAsset', clean: true });
            expect(config.resolve).toEqual({ extensions: ['.tsx', '.ts', '.js'], fallback: { fs: false } });
        });

        it('applies mode and devtool to production builds only (webpack-debug.config.js replaced them)', async () =>
        {
            const analysis = analyzeBase(customizedConfig(`    mode: 'production',\n    devtool: 'source-map'`));
            const customize = loadCustomization(renderWebpackConfig(template, [analysis]));

            expect(analysis.customizations.map((customization) => customization.name)).toEqual(['devtool']);
            expect((await customize(generatedConfig(), { item: { name: 'MyAsset' }, debug: false })).devtool).toBe('source-map');
            expect((await customize(generatedConfig(), { item: { name: 'MyAsset' }, debug: true })).devtool).toBeUndefined();
        });
    });

    describe('webpack-debug.config.js customisations', () =>
    {
        it('applies them to debug builds only', async () =>
        {
            const debugText = interfaceAssetConfig('MyAsset', 'webpack-debug.config.js')
                .replace(`devtool: 'inline-source-map'`, `devtool: 'eval-source-map',\n    optimization: { minimize: false }`);
            const analyses = [analyzeBase(interfaceAssetConfig('MyAsset', 'webpack.config.js')), analyzeDebug(debugText)];

            expect(analyses[1].unsupported).toEqual([]);
            expect(analyses[1].customizations.map((customization) => customization.name)).toEqual(['devtool (debug)', 'optimization (debug)']);
            const rendered = renderWebpackConfig(template, analyses);
            expect(rendered).toBe(withBody([
                '    // Moved from webpack-debug.config.js by intuiface-cli migrate',
                '    if (debug)',
                '    {',
                `        config.devtool = 'eval-source-map';`,
                '        config.optimization = { minimize: false };',
                '    }'
            ].join('\n')));
            const customize = loadCustomization(rendered);
            expect(await customize(generatedConfig(), { item: { name: 'MyAsset' }, debug: false })).toEqual(generatedConfig());
            expect(await customize(generatedConfig(), { item: { name: 'MyAsset' }, debug: true })).toMatchObject({ devtool: 'eval-source-map', optimization: { minimize: false } });
        });

        it('writes a require used by both files once', () =>
        {
            const webpackRequire = `const webpack = require('webpack');\n`;
            const analyses = [
                analyzeBase(customizedConfig(`    plugins2: [new webpack.DefinePlugin({ A: '1' })]`, webpackRequire)),
                analyzeDebug(`${webpackRequire}${interfaceAssetConfig('MyAsset', 'webpack-debug.config.js').replace(`devtool: 'inline-source-map'`, `devtool: 'inline-source-map',\n    other: new webpack.DefinePlugin({ B: '2' })`)}`)
            ];

            const rendered = renderWebpackConfig(template, analyses);

            expect(rendered.match(/require\('webpack'\)/g)).toHaveLength(1);
            expect(analyses.flatMap((analysis) => analysis.unsupported)).toEqual([]);
        });

        it('reports a declaration that differs between the files', () =>
        {
            const analyses = [
                analyzeBase(customizedConfig('    externals: target', `const target = { fs: 'commonjs fs' };\n`)),
                analyzeDebug(`const target = 'web';\n${interfaceAssetConfig('MyAsset', 'webpack-debug.config.js').replace(`devtool: 'inline-source-map'`, `devtool: 'inline-source-map',\n    externals: target`)}`)
            ];

            renderWebpackConfig(template, analyses);

            expect(analyses[1].unsupported).toEqual([`'target' is also declared in webpack.config.js`]);
        });
    });

    describe('changes that cannot be moved', () =>
    {
        it.each([
            [
                'changed ModuleFederationPlugin options',
                interfaceAssetConfig('MyAsset', 'webpack.config.js').replace('strictVersion: false', 'strictVersion: true'),
                'the ModuleFederationPlugin options are changed (the workspace generates this plugin for each item)'
            ],
            [
                'another entry',
                interfaceAssetConfig('MyAsset', 'webpack.config.js').replace(`entry: './src/MyAsset.ts'`, `entry: './src/Other.ts'`),
                '`entry: \'./src/Other.ts\'`: the workspace builds src/MyAsset.ts (set the item "entry" in intuiface.workspace.json)'
            ],
            [
                'another output folder',
                interfaceAssetConfig('MyAsset', 'webpack.config.js').replace(`'dist/MyAsset'`, `'build'`),
                '`output.path: path.resolve(__dirname, \'build\')`: the workspace builds each item in dist/<item name>'
            ],
            [
                'a spread configuration',
                customizedConfig('    ...shared', `const shared = {};\n`),
                '`...shared` cannot be moved automatically'
            ],
            [
                'a configuration function',
                'module.exports = (env) => ({ externals: { fs: \'commonjs fs\' } });',
                '`module.exports` is not assigned a configuration object'
            ],
            [
                'ES module syntax',
                `import webpack from 'webpack';\nmodule.exports = { externals: {} };`,
                `it uses ES module syntax (import webpack from 'webpack';), webpack.config.cjs is a CommonJS module`
            ],
            [
                'a change of module.exports after the object',
                `module.exports = { externals: {} };\nmodule.exports.target = 'node';`,
                `it changes module.exports outside the configuration object (module.exports.target = 'node';)`
            ]
        ])('reports %s', (description, text, reason) =>
        {
            expect(analyzeBase(text).unsupported).toEqual([reason]);
        });

        it('reports a file that cannot be parsed, and moves nothing from it', () =>
        {
            const analysis = analyzeBase('module.exports = { externals: { fs: \'commonjs fs\' }');

            expect(analysis.unsupported).toHaveLength(1);
            expect(analysis.unsupported[0]).toMatch(/^it cannot be parsed \(.+\)$/);
            expect(analysis.customizations).toEqual([]);
        });

        it('still moves the other customisations of the file', () =>
        {
            const analysis = analyzeBase(customizedConfig(`    externals: { fs: 'commonjs fs' }`).replace('strictVersion: false', 'strictVersion: true'));

            expect(analysis.customizations.map((customization) => customization.name)).toEqual(['externals']);
            expect(analysis.unsupported).toHaveLength(1);
        });

        it('reports a debug configuration that does not extend webpack.config.js', () =>
        {
            expect(analyzeDebug(`module.exports = { mode: 'development' };`).unsupported)
                .toEqual([`it does not extend webpack.config.js (\`...require('./webpack.config')\`)`]);
        });

        it('reports a debug configuration that replaces the plugins, or reads the base configuration', () =>
        {
            const debugText = interfaceAssetConfig('MyAsset', 'webpack-debug.config.js')
                .replace(`devtool: 'inline-source-map'`, `devtool: 'inline-source-map',\n    plugins: [],\n    externals: baseConfig.externals`);

            expect(analyzeDebug(debugText).unsupported).toEqual(['`plugins` is replaced for debug builds', '`externals (debug)` uses baseConfig']);
        });

        it('reports a top-level declaration hidden by a parameter of the function', () =>
        {
            expect(analyzeBase(customizedConfig('    devtool: debug', `const debug = true;\n`)).unsupported)
                .toEqual([`'debug' is declared at the top of the file and is also a parameter of the webpack.config.cjs function`]);
        });
    });

    describe('migrateWebpackConfigFiles', () =>
    {
        let dir: string;

        beforeEach(() =>
        {
            dir = createTempDir('cli-webpack-migration');
        });

        afterEach(() =>
        {
            removeTempDir(dir);
        });

        const readText = (file: string): string => toLf(fs.readFileSync(path.join(dir, file), 'utf8'));

        it('replaces the generated files with the webpack.config.cjs template', () =>
        {
            writeFiles(dir, {
                'webpack.config.js': interfaceAssetConfig('MyAsset', 'webpack.config.js'),
                'webpack-debug.config.js': interfaceAssetConfig('MyAsset', 'webpack-debug.config.js')
            });

            const migration = migrateWebpackConfigFiles(dir, 'MyAsset');

            expect(migration).toEqual({
                isWebpackConfigCreated: true,
                migrated: [],
                removedFiles: ['webpack.config.js', 'webpack-debug.config.js'],
                keptFiles: []
            });
            expect(readText('webpack.config.cjs')).toBe(template);
            expect(fs.existsSync(path.join(dir, 'webpack.config.js'))).toBe(false);
            expect(fs.existsSync(path.join(dir, 'webpack-debug.config.js'))).toBe(false);
        });

        it('creates the template when the project has no webpack config', () =>
        {
            expect(migrateWebpackConfigFiles(dir, 'MyAsset')).toEqual({ isWebpackConfigCreated: true, migrated: [], removedFiles: [], keptFiles: [] });
            expect(readText('webpack.config.cjs')).toBe(template);
        });

        it('moves the customisations and removes the files', () =>
        {
            writeFiles(dir, {
                'webpack.config.js': customizedConfig(`    externals: { fs: 'commonjs fs' }`),
                'webpack-debug.config.js': interfaceAssetConfig('MyAsset', 'webpack-debug.config.js')
            });

            const migration = migrateWebpackConfigFiles(dir, 'MyAsset');

            expect(migration.migrated).toEqual(['externals']);
            expect(migration.removedFiles).toEqual(['webpack.config.js', 'webpack-debug.config.js']);
            expect(readText('webpack.config.cjs')).toContain(`    config.externals = { fs: 'commonjs fs' };\n`);
        });

        it('keeps a file with changes that cannot be moved, and moves what it can', () =>
        {
            const legacyConfig = customizedConfig(`    externals: { fs: 'commonjs fs' }`).replace('strictVersion: false', 'strictVersion: true');
            writeFiles(dir, {
                'webpack.config.js': legacyConfig,
                'webpack-debug.config.js': interfaceAssetConfig('MyAsset', 'webpack-debug.config.js')
            });

            const migration = migrateWebpackConfigFiles(dir, 'MyAsset');

            expect(migration.migrated).toEqual(['externals']);
            expect(migration.removedFiles).toEqual(['webpack-debug.config.js']);
            expect(migration.keptFiles).toEqual([{
                file: 'webpack.config.js',
                reasons: ['the ModuleFederationPlugin options are changed (the workspace generates this plugin for each item)']
            }]);
            expect(readText('webpack.config.js')).toBe(legacyConfig);
            expect(readText('webpack.config.cjs')).toContain(`config.externals = { fs: 'commonjs fs' };`);
        });

        it('never overwrites an existing webpack.config.cjs', () =>
        {
            const existing = 'module.exports = (config) => config;\n';
            writeFiles(dir, {
                'webpack.config.cjs': existing,
                'webpack.config.js': customizedConfig(`    externals: { fs: 'commonjs fs' }`),
                'webpack-debug.config.js': interfaceAssetConfig('MyAsset', 'webpack-debug.config.js')
            });

            const migration = migrateWebpackConfigFiles(dir, 'MyAsset');

            expect(readText('webpack.config.cjs')).toBe(existing);
            expect(migration).toEqual({
                isWebpackConfigCreated: false,
                migrated: [],
                removedFiles: ['webpack-debug.config.js'],
                keptFiles: [{ file: 'webpack.config.js', reasons: ['webpack.config.cjs already exists: `externals` not moved'] }]
            });
        });
    });
});
