import fs from 'fs-extra';
import path from 'path';
import { fileURLToPath } from 'url';
import { WorkspaceItem } from '../types.js';

/**
 * Minimum Node.js major version required by the Intuiface CLI and generated workspaces.
 * This is the single source of truth — it drives .nvmrc content, package.json engines,
 * and the startup version check in cli.ts.
 */
export const MIN_NODE_MAJOR = 22;

// eslint-disable-next-line prefer-arrow/prefer-arrow-functions
export function renderWorkspaceItemSource(item: WorkspaceItem): string
{
    if (item.type === 'binding-converter')
    {
        return `import { Converter, Parameter } from '@intuiface/core';\n\nexport class ${item.name} {\n    @Converter({\n        displayName: '${item.name}',\n        description: 'Example binding converter generated by Intuiface CLI.'\n    })\n    public static computeOutput(\n        @Parameter({\n            name: 'input',\n            displayName: 'Input',\n            description: 'Value to convert.',\n            defaultValue: '',\n            type: String\n        }) input: string\n    ): string\n    {\n        return input?.toString() ?? '';\n    }\n}\n`;
    }

    return `import { Action, Asset, IntuifaceElement, Parameter, Property, Trigger } from '@intuiface/core';\n\n@Asset({\n    name: '${item.name}',\n    category: '${item.category ?? ''}',\n    behaviors: []\n})\nexport class ${item.name} extends IntuifaceElement {\n    @Property({\n        displayName: 'propertyExample',\n        description: 'A property declaration example.',\n        defaultValue: 0,\n        minValue: 0,\n        maxValue: 10,\n        type: Number\n    })\n    public propertyExample = 0;\n\n    @Trigger({\n        name: 'exampleTrigger',\n        displayName: 'A Trigger Example',\n        description: 'Raised when the property example changes.'\n    })\n    public exampleTrigger(\n        @Parameter({\n            name: 'triggerParam',\n            displayName: 'Trigger parameter',\n            description: 'A trigger parameter example.',\n            defaultValue: '',\n            type: String\n        }) _triggerParam: string\n    ): void {}\n\n    @Action({\n        displayName: 'Action Example',\n        description: 'An action example with a parameter.',\n        validate: true\n    })\n    public actionExample(\n        @Parameter({\n            name: 'actionParam',\n            displayName: 'Action parameter',\n            description: 'An action parameter example.',\n            defaultValue: 1,\n            minValue: 0,\n            maxValue: 10,\n            type: Number\n        }) actionParam: number\n    ): void\n    {\n        if (this.propertyExample !== actionParam)\n        {\n            this.propertyExample = actionParam;\n            this.exampleTrigger('Example trigger payload');\n        }\n    }\n}\n`;
}

// eslint-disable-next-line prefer-arrow/prefer-arrow-functions
export function buildWorkspaceTsConfig(): string
{
    return `${JSON.stringify({
        compileOnSave: false,
        compilerOptions: {
            experimentalDecorators: true,
            emitDecoratorMetadata: true,
            outDir: './dist',
            noImplicitAny: true,
            target: 'ES2022',
            useDefineForClassFields: false,
            module: 'es2020',
            lib: ['es2018', 'dom'],
            allowJs: true,
            allowSyntheticDefaultImports: true,
            esModuleInterop: true,
            declaration: false,
            downlevelIteration: true,
            moduleResolution: 'node',
            importHelpers: true
        },
        exclude: ['node_modules'],
        include: ['**/src/**/*.ts']
    }, null, 2)}\n`;
}

// eslint-disable-next-line prefer-arrow/prefer-arrow-functions
export function getPublishedPackageVersion(): string
{
    const packageJsonPath = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..', 'package.json');
    const packageJson = fs.readJsonSync(packageJsonPath, { throws: false });
    const version = packageJson?.version;

    return typeof version === 'string' && version !== ''
        ? version
        : 'latest';
}

// eslint-disable-next-line prefer-arrow/prefer-arrow-functions
export function getWorkspaceNodeVersion(): string
{
    // Returns the pinned minimum major version so generated .nvmrc is stable
    // regardless of which Node the developer happened to run the CLI with.
    return `${MIN_NODE_MAJOR}`;
}

// eslint-disable-next-line prefer-arrow/prefer-arrow-functions
export function getWorkspaceNodeEngineRange(): string
{
    return `>=${MIN_NODE_MAJOR}`;
}

// eslint-disable-next-line prefer-arrow/prefer-arrow-functions
export function createWorkspacePackageJson(workspaceName: string): Record<string, unknown>
{
    const version = getPublishedPackageVersion();
    return {
        name: workspaceName,
        version: '1.0.0',
        private: true,
        engines: {
            node: getWorkspaceNodeEngineRange()
        },
        scripts: {
            'build': 'npx intuiface-cli build --all',
            'build:debug': 'npx intuiface-cli build --all --debug'
        },
        dependencies: {
            '@intuiface/cli': version,
            '@intuiface/core': version,
            'tslib': '^2.6.2'
        },
        devDependencies: {
            '@types/node': '^22.10.1',
            'ts-loader': '^9.5.1',
            'typescript': '^5.8.0',
            'webpack': '^5.99.0',
            'webpack-cli': '^6.0.1'
        }
    };
}
